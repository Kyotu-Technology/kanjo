#!/bin/sh
# Regenerates the TypeScript bindings from crates/kanjo-core/src/api.rs and the
# barrel file the web UI imports from.
set -eu
root="$(cd "$(dirname "$0")/.." && pwd)"
dir="$root/web/src/lib/api"
rm -rf "$dir/bindings"
(cd "$root" && cargo test -q -p kanjo-core export_bindings >/dev/null)
{
  echo "// Re-exports the types generated from crates/kanjo-core/src/api.rs and settings.rs."
  echo "// Generated by scripts/gen-bindings.sh. Import API types from here, never from the bindings directory directly."
  for f in "$dir"/bindings/*.ts; do
    n="$(basename "$f" .ts)"
    echo "export type { $n } from './bindings/$n';"
  done
  echo "export type { JsonValue } from './bindings/serde_json/JsonValue';"
} > "$dir/contract.ts"
