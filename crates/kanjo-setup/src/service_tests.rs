#[test]
fn linux_install_status_uninstall() {
    let dir = tempfile::tempdir().unwrap();
    let target = Target { platform: Platform::Linux, dir: dir.path().join("systemd/user") };
    let runner = FakeRunner::with(vec![("systemctl --user is-active", out(0, "active\n"))]);
    assert_eq!(status_with(&target, &runner), ServiceState::NotInstalled);
    install_with(&target, &runner, Path::new("/usr/bin/kanjo"), &unix_paths()).unwrap();
    assert!(std::fs::read_to_string(target.file()).unwrap().contains("ExecStart=\"/usr/bin/kanjo\" serve"));
    assert_eq!(status_with(&target, &runner), ServiceState::Running);
    uninstall_with(&target, &runner).unwrap();
    assert!(!target.file().exists());
    assert_eq!(
        runner.calls(),
        [
            "systemctl --user daemon-reload",
            "systemctl --user enable kanjo.service",
            "systemctl --user restart kanjo.service",
            "systemctl --user is-active kanjo.service",
            "systemctl --user disable --now kanjo.service",
            "systemctl --user daemon-reload",
        ]
    );
    uninstall_with(&target, &runner).unwrap();
    assert_eq!(runner.calls().len(), 6);

    let stopped = FakeRunner::with(vec![("systemctl --user is-active", out(3, "inactive\n"))]);
    install_with(&target, &stopped, Path::new("/usr/bin/kanjo"), &unix_paths()).unwrap();
    assert_eq!(status_with(&target, &stopped), ServiceState::Stopped);
}

#[test]
fn linux_install_reports_failures() {
    let dir = tempfile::tempdir().unwrap();
    let target = Target { platform: Platform::Linux, dir: dir.path().to_path_buf() };
    let runner = FakeRunner::with(vec![(
        "systemctl --user daemon-reload",
        RunOutput { code: Some(1), stdout: String::new(), stderr: "Failed to connect to bus".into() },
    )]);
    let err = install_with(&target, &runner, Path::new("/usr/bin/kanjo"), &unix_paths()).unwrap_err();
    assert!(err.to_string().contains("Failed to connect to bus"), "{err}");
}

#[test]
fn macos_install_status_uninstall() {
    let dir = tempfile::tempdir().unwrap();
    let home = dir.path().join("data");
    let paths = Paths::at(&home, dir.path().join("claude"));
    let target = Target { platform: Platform::MacOs, dir: dir.path().join("LaunchAgents") };
    let runner =
        FakeRunner::with(vec![("id -u", out(0, "501\n")), ("launchctl print", out(0, "gui/501/io.kyotu.kanjo = {\n\tstate = running\n}"))]);
    install_with(&target, &runner, Path::new("/usr/local/bin/kanjo"), &paths).unwrap();
    assert!(target.file().ends_with("io.kyotu.kanjo.plist") && target.file().is_file());
    assert!(paths.log_dir().is_dir());
    assert_eq!(status_with(&target, &runner), ServiceState::Running);
    uninstall_with(&target, &runner).unwrap();
    let plist = target.file().to_string_lossy().into_owned();
    assert_eq!(
        runner.calls(),
        [
            "id -u".to_string(),
            "launchctl bootout gui/501/io.kyotu.kanjo".into(),
            format!("launchctl bootstrap gui/501 {plist}"),
            "launchctl enable gui/501/io.kyotu.kanjo".into(),
            "id -u".into(),
            "launchctl print gui/501/io.kyotu.kanjo".into(),
            "id -u".into(),
            "launchctl bootout gui/501/io.kyotu.kanjo".into(),
        ]
    );
    assert!(!target.file().exists());
}

#[test]
fn windows_install_status_uninstall() {
    let dir = tempfile::tempdir().unwrap();
    let target = Target { platform: Platform::Windows, dir: dir.path().join("service") };
    let paths = Paths::at(dir.path().join("data"), dir.path().join("claude"));
    let runner = FakeRunner::default();
    install_with(&target, &runner, Path::new(r"C:\Program Files\Kanjo\kanjo.exe"), &paths).unwrap();
    assert_eq!(status_with(&target, &runner), ServiceState::Installed);
    let vbs = target.file().to_string_lossy().into_owned();
    uninstall_with(&target, &runner).unwrap();
    assert!(!target.file().exists());
    let run = r"HKCU\Software\Microsoft\Windows\CurrentVersion\Run";
    assert_eq!(
        runner.calls(),
        [
            format!("reg add {run} /v Kanjo /t REG_SZ /d wscript.exe //B //Nologo \"{vbs}\" /f"),
            format!("wscript.exe //B //Nologo {vbs}"),
            format!("reg query {run} /v Kanjo"),
            format!("reg query {run} /v Kanjo"),
            format!("reg delete {run} /v Kanjo /f"),
        ]
    );
    let missing = FakeRunner::with(vec![("reg query", out(1, ""))]);
    assert_eq!(status_with(&target, &missing), ServiceState::NotInstalled);
    uninstall_with(&target, &missing).unwrap();
}
