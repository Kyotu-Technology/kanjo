use super::*;
use std::sync::Mutex;

#[derive(Default)]
struct FakeRunner {
    calls: Mutex<Vec<String>>,
    replies: Vec<(&'static str, RunOutput)>,
}

impl FakeRunner {
    fn with(replies: Vec<(&'static str, RunOutput)>) -> FakeRunner {
        FakeRunner { calls: Mutex::new(Vec::new()), replies }
    }

    fn calls(&self) -> Vec<String> {
        self.calls.lock().unwrap().clone()
    }
}

impl Runner for FakeRunner {
    fn run(&self, program: &str, args: &[&str]) -> std::io::Result<RunOutput> {
        let line = format!("{program} {}", args.join(" "));
        self.calls.lock().unwrap().push(line.clone());
        Ok(self
            .replies
            .iter()
            .find(|(prefix, _)| line.starts_with(prefix))
            .map(|(_, o)| o.clone())
            .unwrap_or(RunOutput { code: Some(0), ..Default::default() }))
    }
}

fn out(code: i32, stdout: &str) -> RunOutput {
    RunOutput { code: Some(code), stdout: stdout.into(), stderr: String::new() }
}

fn unix_paths() -> Paths {
    Paths::at("/home/dev/.local/share/kanjo", "/home/dev/.claude")
}

#[test]
fn systemd_unit_snapshot() {
    let unit = systemd_unit(Path::new("/home/dev/.cargo/bin/kanjo"), &unix_paths());
    assert_eq!(
        unit,
        r#"[Unit]
Description=Kanjo cost and limit monitor for Claude Code
Documentation=https://github.com/Kyotu-Technology/kanjo

[Service]
Type=simple
ExecStart="/home/dev/.cargo/bin/kanjo" serve
Environment="KANJO_HOME=/home/dev/.local/share/kanjo"
Environment="KANJO_CLAUDE_DIR=/home/dev/.claude"
Restart=on-failure
RestartSec=10

[Install]
WantedBy=default.target
"#
    );
    let odd = systemd_unit(Path::new("/opt/my tools/100%/$bin/kanjo"), &Paths::at("/data/$x%", "/c\"d"));
    assert!(odd.contains(r#"ExecStart="/opt/my tools/100%%/$$bin/kanjo" serve"#), "{odd}");
    assert!(odd.contains(r#"Environment="KANJO_HOME=/data/$x%%""#) && odd.contains(r#"Environment="KANJO_CLAUDE_DIR=/c\"d""#));
}

